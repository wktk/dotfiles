#!/bin/bash

# The links and the cleanup below use paths relative to this repository.
cd "$(dirname "$0")" || exit 1

DOTFILES="
  .actrc
  .asdfrc
  .bash_profile
  .bashrc
  .bin
  .claude/statusline-command.sh
  .config/git/ignore
  .gitconfig
  .inputrc
  .tmux
  .tmux.conf
  .tmux-pbcopy.conf
  .vim
  .vimrc
  .zshenv
  .zshrc
"

RETIRED="
  .profile
  .oh-my-zsh
  .zprezto
  .zlogin
  .zlogout
  .zpreztorc
  .zprofile
"

# Stop if $HOME links into another clone (e.g. running this from a worktree):
# links would be skipped while the cleanup below archives that clone's files.
for dotfile in $DOTFILES $RETIRED; do
  target="$(readlink "$HOME/$dotfile")" || continue
  case "$target" in
    "$(pwd)"/*) continue ;;
  esac
  # Entries may be nested (e.g. .claude/statusline-command.sh), so strip the
  # whole entry path to get the clone that the link points into.
  clone="${target%/$dotfile}"
  if [ "$clone" != "$target" ] && [ -f "$clone/setup.sh" ]; then
    echo "Abort: $HOME/$dotfile links to $clone; run setup.sh there." >&2
    exit 1
  fi
done

# Other tools also write to these, so an existing file is merged into this
# repository by hand rather than renamed to .bak.
MERGE_BY_HAND="
  .config/git/ignore
"
for dotfile in $MERGE_BY_HAND; do
  if [ -f "$HOME/$dotfile" ] && [ ! -h "$HOME/$dotfile" ] && ! cmp -s "$HOME/$dotfile" "$dotfile"; then
    echo "Abort: merge $HOME/$dotfile into $(pwd)/$dotfile, remove it, and run setup.sh again." >&2
    exit 1
  fi
done

# Servers may get a copy of this repository without .git (e.g. via rsync).
if [ -e .git ]; then
  git submodule update --init --recursive
  # Check out new submodule commits on pull as well, not only fetch them.
  git config submodule.recurse true
fi

if [ "$(uname)" = "Darwin" ] && command -v brew > /dev/null; then
  brew install \
    asdf \
    font-biz-udgothic \
    font-udev-gothic \
    font-udev-gothic-nf \
    fzf \
    zoxide \
    zsh-completions \

  # compinit rejects zsh-completions while its parent directory is group-writable.
  # Only the owner can change it, e.g. not when another user installed Homebrew.
  if [ -O "$(brew --prefix)/share" ]; then
    chmod go-w "$(brew --prefix)/share"
  fi
fi

for dotfile in $DOTFILES; do
  if [ -h "$HOME/$dotfile" ]; then
    echo "Skip: $dotfile (already linked to somewhere)"
    continue
  fi

  if [ -f "$HOME/$dotfile" ] && cmp -s "$HOME/$dotfile" "$dotfile"; then
    # Same content as this repository has, so nothing is lost.
    echo "Replace: $dotfile (identical to the repository's)"
    rm "$HOME/$dotfile"
  elif [ -e "$HOME/$dotfile" ]; then
    echo "Backup: $dotfile -> $dotfile.bak (Existing file renamed)"
    mv "$HOME/$dotfile"{,.bak}
  fi

  # Some entries live in a subdirectory, e.g. .claude/statusline-command.sh.
  mkdir -p "$(dirname "$HOME/$dotfile")"
  ln -s "$(pwd)/$dotfile" "$HOME/$dotfile"
  echo "Created: $dotfile"
done

for retired in $RETIRED; do
  if [ -h "$HOME/$retired" ]; then
    case "$(readlink "$HOME/$retired")" in
      "$(pwd)"/*)
        # Its content is kept in this repository's history.
        echo "Remove: $HOME/$retired"
        rm "$HOME/$retired"
        ;;
      *)
        echo "Archive: $HOME/$retired"
        mv "$HOME/$retired" "$HOME/$retired.$(date +'%y%m%d%H%M%S').bak"
        ;;
    esac
  fi
done

# Migration from prezto (2026-11). Remove this block once every machine has
# run setup.sh after the migration.
rm -rf .zprezto .git/modules/.zprezto "$HOME/.cache/prezto"
if [ -e .git ]; then
  git config --remove-section submodule..zprezto 2> /dev/null
fi
# Files generated by fzf's install script; .shell/rc.sh uses `fzf --zsh` /
# `fzf --bash` instead when fzf supports them.
for shell in zsh bash; do
  if [ -f "$HOME/.fzf.$shell" ] && fzf --$shell > /dev/null 2>&1; then
    echo "Remove: $HOME/.fzf.$shell"
    rm "$HOME/.fzf.$shell"
  fi
done

echo "done."
